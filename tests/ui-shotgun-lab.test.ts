import { beforeAll,afterAll,it,expect } from 'vitest';
import { chromium,type Browser } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { openRenderer } from './renderer-harness.js';
import { compileDualWingPlan } from '../src/dual-wing-plan.js';
import { bookingView,defaultSetup } from '../ui/booking.js';
import { ConfigSchema } from '../src/config.js';
let browser:Browser;
beforeAll(async()=>{browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'chrome'}:{})});});afterAll(async()=>{await browser.close();});
it('edits and reopens exact dual-wing allocation, shows blocked live status and preserves the legacy save',async()=>{
  const page=await openRenderer(browser,{booking:bookingView(ConfigSchema.parse({...defaultSetup,PLAYER_FULL_NAME:'Fixture',PLAYER_PHONE:'09000000000',PLAYER_EMAIL:'offline@example.invalid'}))},'lab');
  await page.exposeFunction('nodeLabPreview',compileDualWingPlan);
  await page.waitForFunction(()=>document.querySelectorAll('.lab-target').length===2);
  expect(await page.locator('#lab-policy').innerText()).toContain('PROVISIONAL');
  await page.locator('#lab-review').click();await page.waitForFunction(()=>document.getElementById('lab-review-output')?.textContent?.includes('8 aggregate attempts'));
  expect(await page.locator('#lab-review-output').innerText()).toContain('2026-10-21');
  await page.locator('#lab-allocation').selectOption('CUSTOM');
  await page.locator('#lab-count-0').fill('3');await page.locator('#lab-count-0').dispatchEvent('change');
  await page.locator('#lab-count-1').fill('2');await page.locator('#lab-count-1').dispatchEvent('change');
  await page.locator('#lab-save').click();await page.waitForFunction(()=>(window as any).fixtureLabSaved);
  expect(await page.evaluate(()=>(window as any).fixtureCalls.includes('saveBooking'))).toBe(false);
  await page.locator('#lab-load').click();await page.waitForFunction(()=>document.getElementById('lab-status')?.textContent?.includes('saved'));
  expect(await page.locator('#lab-count-0').inputValue()).toBe('3');expect(await page.locator('#lab-count-1').inputValue()).toBe('2');
  expect(await page.locator('#view-lab').innerText()).toContain('one real pending booking');
  await mkdir('.local/dual-wing/screenshots',{recursive:true});await page.screenshot({path:'.local/dual-wing/screenshots/lab-wide.png',fullPage:true});
  await page.setViewportSize({width:560,height:900});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'.local/dual-wing/screenshots/lab-narrow.png',fullPage:true});await page.close();
});
